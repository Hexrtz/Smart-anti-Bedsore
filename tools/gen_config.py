#!/usr/bin/env python3
"""สร้าง shared/config.h จาก shared/config.yaml ให้ฝั่ง ESP32 ใช้ค่าเดียวกับ Gateway

ใช้: python tools/gen_config.py
"""
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "shared" / "config.yaml"
DST = ROOT / "shared" / "config.h"


def c_value(v):
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return '"' + v.replace('"', '\\"') + '"'
    if isinstance(v, list):
        return "{" + ", ".join(c_value(x) for x in v) + "}"
    raise TypeError(f"unsupported value: {v!r}")


def flatten(d, prefix=""):
    for k, v in d.items():
        name = f"{prefix}_{k}" if prefix else k
        if isinstance(v, dict):
            yield from flatten(v, name)
        else:
            yield name.upper(), v


def main():
    cfg = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    lines = [
        "// AUTO-GENERATED by tools/gen_config.py from shared/config.yaml",
        "// ห้ามแก้ไฟล์นี้ด้วยมือ ให้แก้ config.yaml แล้วรันสคริปต์ใหม่",
        "#pragma once",
        "",
    ]
    for name, v in flatten(cfg):
        if isinstance(v, list):
            lines.append(f"#define CFG_{name}_COUNT {len(v)}")
        lines.append(f"#define CFG_{name} {c_value(v)}")
    DST.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
