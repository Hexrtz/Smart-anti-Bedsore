"""Export a trained run to TensorFlow Lite Micro (int8) for the ESP32-S3.

    PyTorch model.pt -> ONNX -> onnx2tf (TF SavedModel, NHWC) -> TFLite full-int8 -> C array

Only the classifier is exported. The log-mel front end (Hamming taper, STFT,
mel filterbank, log, per-bin normalisation) runs in firmware before the model;
every constant it needs is written to cough_features.h so firmware and
training cannot drift apart.

Usage (run from node2/experiment, needs the "tflite" dependency group):
    uv run --group tflite python src/export_tflite.py                      # latest run of every config
    uv run --group tflite python src/export_tflite.py --run runs/cnn/20261112-175155
    make export RUN=runs/cnn/20261112-175155

Writes runs/<name>/<time>/tflite/:
  model.onnx                 float model, input [1, 1, n_mels, frames] (NCHW)
  saved_model/               onnx2tf output (NHWC) + float32 .tflite
  cough_<name>_int8.tflite   full-integer model: int8 input [1, n_mels, frames, 1], int8 logits
  cough_model_data.h         the .tflite as a 16-byte aligned C array (for TFLite Micro)
  cough_features.h           front-end constants + input/output quantization + ops to register
  cough_test_vector.h        one val window per class: raw int16 audio, expected int8 input and output
  export.json                PyTorch float vs TFLite int8 on val and test, sizes, ops
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import sys
import warnings
from pathlib import Path

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "3")
warnings.filterwarnings("ignore")

import numpy as np  # noqa: E402
import torch  # noqa: E402
from torch import nn  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
from coughml.data import load_splits, to_float  # noqa: E402
from coughml.infer import load_run  # noqa: E402
from coughml.metrics import evaluate  # noqa: E402
from coughml.models import CNN, MLP  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]  # node2/experiment
KEYS = ("accuracy", "macro_f1", "cough_recall", "cough_precision", "cough_f1")


class Net4D(nn.Module):
    """Classifier only, input [batch, 1, n_mels, frames] (NCHW, C = 1)."""

    def __init__(self, net: nn.Module):
        super().__init__()
        self.net = net

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        if isinstance(self.net, CNN):
            return self.net.head(self.net.features(x))
        if isinstance(self.net, MLP):
            return self.net.net(x)  # Flatten handles the 4-D input
        raise TypeError(type(self.net))


def latest_runs() -> list[Path]:
    out = []
    for d in sorted(p for p in (ROOT / "runs").iterdir() if p.is_dir() and not p.name.startswith("_")):
        runs = sorted(r for r in d.iterdir() if (r / "model.pt").exists())
        if runs:
            out.append(runs[-1])
    return out


@torch.no_grad()
def logmel(model, split, clip_s: float, idx: np.ndarray | None = None) -> np.ndarray:
    """Normalised log-mel, NHWC [n, n_mels, frames, 1] float32, centred 1 s windows."""
    rng = np.random.default_rng(0)
    idx = np.arange(len(split)) if idx is None else idx
    out = []
    for i in range(0, len(idx), 512):
        w = to_float(split.windows(idx[i:i + 512], clip_s, train=False, rng=rng), torch.device("cpu"))
        out.append(model.feat(w).unsqueeze(-1).numpy())
    return np.concatenate(out).astype(np.float32)


def c_floats(name: str, values, per_line: int = 8) -> str:
    def lit(x: float) -> str:  # valid C float literal: 0 -> 0.0f, 1e-06 stays 1e-06f
        t = f"{x:.9g}"
        return (t if any(ch in t for ch in ".en") else t + ".0") + "f"
    v = [lit(x) for x in np.asarray(values, dtype=np.float64).ravel()]
    lines = [", ".join(v[i:i + per_line]) for i in range(0, len(v), per_line)]
    return f"static const float {name}[{len(v)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


def model_data_header(tflite_bytes: bytes, run: Path) -> str:
    hexes = [f"0x{b:02x}" for b in tflite_bytes]
    body = ",\n    ".join(", ".join(hexes[i:i + 12]) for i in range(0, len(hexes), 12))
    return f"""// Generated by node2/experiment/src/export_tflite.py from {run.relative_to(ROOT)}
// int8 TFLite model for TensorFlow Lite Micro. {len(tflite_bytes)} bytes.
#ifndef COUGH_MODEL_DATA_H
#define COUGH_MODEL_DATA_H

alignas(16) const unsigned char g_cough_model[] = {{
    {body}
}};
const unsigned int g_cough_model_len = {len(tflite_bytes)};

#endif  // COUGH_MODEL_DATA_H
"""


def features_header(model, cfg: dict, classes: list[str], run: Path, inp: dict, outp: dict,
                    ops: list[str]) -> str:
    f = cfg["features"]
    feat = model.feat
    n_fft, win = f["n_fft"], f["win_length"]
    hann = torch.hann_window(win, periodic=True)  # torch.stft centres it inside n_fft
    left = (n_fft - win) // 2
    stft_win = torch.zeros(n_fft)
    stft_win[left:left + win] = hann
    fb = feat.mel.mel_scale.fb.numpy()  # [n_fft/2 + 1, n_mels]
    hamming = f.get("taper", "hamming") == "hamming"
    cls = ", ".join(f'"{c}"' for c in classes)
    (in_scale, in_zp), (out_scale, out_zp) = inp["quantization"], outp["quantization"]
    ops_txt = "\n".join(f"//   {o}" for o in ops)
    return f"""// Generated by node2/experiment/src/export_tflite.py from {run.relative_to(ROOT)}
// Log-mel front end + quantization for cough_model_data.h. Must match coughml/features.py.
//
// Per 1 s window of int16 audio at {f['sample_rate']} Hz:
//   1. x[n] = sample[n] / 32768.0f
//   2. taper: {"x[n] *= 0.54f - 0.46f * cosf(2*PI*n / (COUGH_CLIP_SAMPLES - 1))   (Hamming, symmetric)" if hamming else "none"}
//   3. frames t = 0 .. COUGH_FRAMES-1, start = t * COUGH_HOP_LENGTH, length COUGH_N_FFT (no centre padding)
//      frame[k] = x[start + k] * cough_stft_window[k]
//   4. power[b] = |FFT(frame)[b]|^2, b = 0 .. COUGH_N_FFT/2
//   5. mel[m] = sum_b power[b] * cough_mel_fb[b * COUGH_N_MELS + m]
//   6. logmel = logf(mel[m] + COUGH_LOG_EPS)
//   7. v = (logmel - cough_mean[m]) / cough_std[m]
//   8. input int8 at [m][t] (index m * COUGH_FRAMES + t):
//      q = clamp(roundf(v / COUGH_INPUT_SCALE) + COUGH_INPUT_ZERO_POINT, -128, 127)
// Model input tensor: int8 [1, COUGH_N_MELS, COUGH_FRAMES, 1] (NHWC: mel-major, frames contiguous)
// Model output: int8 logits [1, COUGH_N_CLASSES]; class = argmax, or
//   logit = (q - COUGH_OUTPUT_ZERO_POINT) * COUGH_OUTPUT_SCALE, then softmax for probabilities.
//
// Ops to add to tflite::MicroMutableOpResolver:
{ops_txt}
#ifndef COUGH_FEATURES_H
#define COUGH_FEATURES_H

#define COUGH_SAMPLE_RATE       {f['sample_rate']}
#define COUGH_CLIP_SAMPLES      {feat.clip_samples}
#define COUGH_N_FFT             {n_fft}
#define COUGH_WIN_LENGTH        {win}
#define COUGH_HOP_LENGTH        {f['hop_length']}
#define COUGH_N_MELS            {feat.n_mels}
#define COUGH_FRAMES            {feat.frames}
#define COUGH_N_BINS            {n_fft // 2 + 1}
#define COUGH_LOG_EPS           {float(feat.eps)!r}f
#define COUGH_TAPER_HAMMING     {1 if hamming else 0}
#define COUGH_N_CLASSES         {len(classes)}
#define COUGH_INPUT_SCALE       {in_scale:.9g}f
#define COUGH_INPUT_ZERO_POINT  {in_zp}
#define COUGH_OUTPUT_SCALE      {out_scale:.9g}f
#define COUGH_OUTPUT_ZERO_POINT {out_zp}

static const char *const cough_classes[COUGH_N_CLASSES] = {{{cls}}};

// Hann({win}, periodic) zero-padded to {n_fft}, starting at index {left}
{c_floats("cough_stft_window", stft_win.numpy())}
// mel filterbank, row-major [COUGH_N_BINS][COUGH_N_MELS] (torchaudio, HTK mel scale, no norm)
{c_floats("cough_mel_fb", fb)}
// per-mel-bin normalisation from the training set
{c_floats("cough_mean", feat.mean.squeeze(1).numpy())}
{c_floats("cough_std", feat.std.squeeze(1).numpy())}
#endif  // COUGH_FEATURES_H
"""


def test_vector_header(split, classes: list[str], clip_s: float, model, interp, run: Path) -> str:
    """First val window of every class: audio, expected model input and output, for on-device checks."""
    inp, outp = interp.get_input_details()[0], interp.get_output_details()[0]
    scale, zp = inp["quantization"]
    rng = np.random.default_rng(0)
    parts, names, labels = [], [], []
    for ci, c in enumerate(classes):
        for i in np.flatnonzero(split.y == ci)[:200]:   # first window of this class the int8 model gets right
            i = int(i)
            audio = split.windows(np.array([i]), clip_s, train=False, rng=rng)[0]        # int16 [16000]
            with torch.no_grad():
                v = model.feat(to_float(audio[None], torch.device("cpu")))[0].numpy()    # [n_mels, frames]
            q = np.clip(np.round(v / scale) + zp, -128, 127).astype(np.int8)
            interp.set_tensor(inp["index"], q[None, :, :, None])
            interp.invoke()
            o = interp.get_tensor(outp["index"])[0].astype(int)
            if int(np.argmax(o)) == ci:
                break
        names.append(f"tv_{c}")
        labels.append(ci)
        a = ", ".join(str(int(x)) for x in audio)
        qi = ", ".join(str(int(x)) for x in q.ravel())
        parts.append(f"""// {c}: {split.meta.loc[i, 'clip_path']}
static const int16_t tv_{c}_audio[{audio.size}] = {{{a}}};
static const int8_t tv_{c}_input[{q.size}] = {{{qi}}};
static const int8_t tv_{c}_output[{o.size}] = {{{", ".join(map(str, o))}}};
""")
    table = ",\n    ".join(f"{{{lb}, {n}_audio, {n}_input, {n}_output}}" for lb, n in zip(labels, names))
    return f"""// Generated by node2/experiment/src/export_tflite.py from {run.relative_to(ROOT)}
// Golden test vectors: run the front end on *_audio, compare with *_input
// (expect at most +-1 per value from float rounding), run the model on
// *_input, compare with *_output (TFLite reference kernels on the PC).
#ifndef COUGH_TEST_VECTOR_H
#define COUGH_TEST_VECTOR_H
#include <stdint.h>

{"".join(parts)}
struct CoughTestVector {{ int label; const int16_t *audio; const int8_t *input; const int8_t *output; }};
static const CoughTestVector cough_test_vectors[] = {{
    {table}
}};
static const int cough_n_test_vectors = {len(names)};

#endif  // COUGH_TEST_VECTOR_H
"""


def run_tflite(interp, x: np.ndarray) -> np.ndarray:
    """Predicted class per row of x (float NHWC); quantizes the input like the firmware does."""
    inp, out = interp.get_input_details()[0], interp.get_output_details()[0]
    scale, zp = inp["quantization"]
    preds = np.empty(len(x), dtype=np.int64)
    for i in range(len(x)):
        xi = x[i:i + 1]
        if inp["dtype"] == np.int8:
            xi = np.clip(np.round(xi / scale) + zp, -128, 127).astype(np.int8)
        interp.set_tensor(inp["index"], xi)
        interp.invoke()
        preds[i] = int(np.argmax(interp.get_tensor(out["index"])[0]))
    return preds


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", type=Path, action="append", help="run folder (repeatable); default: latest per config")
    ap.add_argument("--calib", type=int, default=1024, help="training windows for int8 calibration")
    args = ap.parse_args()

    import onnx2tf
    import tensorflow as tf
    from ai_edge_litert.interpreter import Interpreter, OpResolverType
    # reference kernels, no XNNPACK delegate: closest to TFLite Micro and lists the real ops
    ref = {"experimental_op_resolver_type": OpResolverType.BUILTIN_REF}
    logging.getLogger("tensorflow").setLevel(logging.ERROR)

    runs = [r if r.is_absolute() else ROOT / r for r in (args.run or latest_runs())]
    if not runs:
        print("no runs found, run `make train` first", file=sys.stderr)
        return 1
    cache = {}
    for run in runs:
        model, cfg, classes = load_run(run, "cpu")
        name = cfg["name"]
        out = run / "tflite"
        out.mkdir(exist_ok=True)
        key = (cfg["data"]["clips_csv"], cfg["data"]["processed_dir"])
        if key not in cache:
            cache[key] = load_splits(ROOT / key[0], ROOT / key[1], classes, cfg["features"]["sample_rate"])
        splits, clip_s = cache[key], cfg["features"]["clip_s"]
        n_mels, frames = model.feat.n_mels, model.feat.frames

        # 1. ONNX (float, NCHW)
        net = Net4D(model.net).eval()
        onnx_file = out / "model.onnx"
        torch.onnx.export(net, torch.zeros(1, 1, n_mels, frames), str(onnx_file), input_names=["logmel"],
                          output_names=["logits"], opset_version=17, dynamo=False)

        # 2. onnx2tf -> SavedModel (NHWC input [1, n_mels, frames, 1])
        sm = out / "saved_model"
        onnx2tf.convert(input_onnx_file_path=str(onnx_file), output_folder_path=str(sm),
                        copy_onnx_input_output_names_to_tflite=True, non_verbose=True)

        # 3. full-integer int8 TFLite, calibrated on training windows
        rng = np.random.default_rng(cfg["seed"])
        tr = splits["train"]
        cidx = np.sort(rng.choice(len(tr), size=min(args.calib, len(tr)), replace=False))
        calib = logmel(model, tr, clip_s, cidx)

        def representative():
            for i in range(len(calib)):
                yield [calib[i:i + 1]]

        conv = tf.lite.TFLiteConverter.from_saved_model(str(sm))
        conv.optimizations = [tf.lite.Optimize.DEFAULT]
        conv.representative_dataset = representative
        conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
        conv.inference_input_type = tf.int8
        conv.inference_output_type = tf.int8
        tfl = conv.convert()
        tfl_file = out / f"cough_{name}_int8.tflite"
        tfl_file.write_bytes(tfl)

        interp = Interpreter(model_content=tfl, **ref)
        interp.allocate_tensors()
        inp, outp = interp.get_input_details()[0], interp.get_output_details()[0]
        assert list(inp["shape"]) == [1, n_mels, frames, 1], f"unexpected TFLite input {inp['shape']}"
        ops = sorted({d["op_name"] for d in interp._get_ops_details()})

        float_tfl = next(sm.glob("*_float32.tflite"), None)
        f_interp = None
        if float_tfl:
            f_interp = Interpreter(model_path=str(float_tfl), **ref)
            f_interp.allocate_tensors()

        # 4. PyTorch float vs TFLite int8 (and float TFLite as a conversion check)
        report = {"run": str(run.relative_to(ROOT)), "calibration_windows": len(cidx),
                  "tflite_kb": round(len(tfl) / 1024, 1), "onnx_kb": round(onnx_file.stat().st_size / 1024, 1),
                  "input": {"shape": [int(s) for s in inp["shape"]], "dtype": "int8",
                            "scale": float(inp["quantization"][0]), "zero_point": int(inp["quantization"][1])},
                  "output": {"shape": [int(s) for s in outp["shape"]], "dtype": "int8",
                             "scale": float(outp["quantization"][0]), "zero_point": int(outp["quantization"][1])},
                  "ops": ops}
        with torch.no_grad():
            for split in ("val", "test"):
                x = logmel(model, splits[split], clip_s)
                y = splits[split].y
                xt = torch.from_numpy(x).permute(0, 3, 1, 2)  # back to NCHW for PyTorch
                pf = torch.cat([net(xt[i:i + 512]).argmax(1) for i in range(0, len(xt), 512)]).numpy()
                pq = run_tflite(interp, x)
                mf, mq = evaluate(y, pf, classes), evaluate(y, pq, classes)
                r = {"pytorch_float32": {k: mf[k] for k in KEYS}, "tflite_int8": {k: mq[k] for k in KEYS},
                     "drop_pp": {k: round((mf[k] - mq[k]) * 100, 2) for k in KEYS},
                     "prediction_agreement": round(float((pf == pq).mean()), 4),
                     "int8_confusion": mq["confusion_matrix"]}
                if f_interp is not None and split == "val":
                    r["float_tflite_agreement"] = round(float((run_tflite(f_interp, x) == pf).mean()), 4)
                report[split] = r
        (out / "export.json").write_text(json.dumps(report, indent=2))
        (out / "cough_model_data.h").write_text(model_data_header(tfl, run))
        (out / "cough_features.h").write_text(features_header(model, cfg, classes, run, inp, outp, ops))
        (out / "cough_test_vector.h").write_text(test_vector_header(splits["val"], classes, clip_s, model, interp, run))

        v = report["val"]
        print(f"\n{run.relative_to(ROOT)}  [{cfg['model']['name']}]  -> {tfl_file.relative_to(ROOT)} "
              f"({report['tflite_kb']} KB)")
        print(f"   input int8 {report['input']['shape']} scale {report['input']['scale']:.6g} "
              f"zp {report['input']['zero_point']}   ops: {', '.join(ops)}")
        if "float_tflite_agreement" in v:
            print(f"   conversion check: float TFLite == PyTorch on {v['float_tflite_agreement'] * 100:.2f}% of val")
        print(f"   {'val':16s}{'float32':>10s}{'int8':>10s}{'drop (pp)':>11s}")
        for k in KEYS:
            print(f"   {k:16s}{v['pytorch_float32'][k]:>10.4f}{v['tflite_int8'][k]:>10.4f}{v['drop_pp'][k]:>11.2f}")
        print(f"   prediction agreement: {v['prediction_agreement']:.4f}   "
              f"(test acc drop {report['test']['drop_pp']['accuracy']:.2f} pp)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
